class BitShift {

    void shiftExample() {

        int number = 8;

        int leftShift = number << 2;
        int rightShift = number >> 2;

        System.out.println("Original Number: " + number);
        System.out.println("Left Shift: " + leftShift);
        System.out.println("Right Shift: " + rightShift);
    }
}